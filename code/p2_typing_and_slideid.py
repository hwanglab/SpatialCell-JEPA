    mu_dirs = [d.strip() for d in a.mu_dir.split(",") if d.strip()]
    agg_dirs = [d.strip() for d in a.agg_dir.split(",") if d.strip()] or None
    niche_dirs = [d.strip() for d in a.niche_dir.split(",") if d.strip()] or None
    D = build(a.cache, mu_dirs, a.labels, a.fov, a.k, a.per_slide, a.seed, slides, agg_dirs,
              niche_dirs)

    # ---------- (1) TYPING: within-fold leave-one-slide-out (Trap 1)
    rows = []
    pc_rows = []          # per-cell dump blocks; stays empty unless --dump-percell
    for arm in ARMS:
        for fname, g in folds:
            for held in g:
                # TWO MODES, and conflating them is what killed 13607051:
                #  * fold-lists given -> fold is a GROUP of slides; train on the OTHERS IN THAT FOLD
                #    only. That is the Trap-1 guard: mu for a slide in fold B came from the
                #    fold-A-trained model, so training the probe across folds leaks the held-out
                #    slide into the features of the other fold.
                #  * no fold-lists (corpus-trained model) -> each "fold" is ONE slide, so
                #    `others in the fold` is EMPTY. There is no leak to guard against because the
                #    predictor never saw ANY eval slide, so train on ALL other slides -> plain
                #    12-fold LOPO with 11 training slides.
                tr = ([s for s in g if s != held] if len(g) > 1
                      else [x for x in slides if x != held])
                # guard added 2026-08-15 with the fold fix: an empty training set is the failure
                # mode that killed 13607051, and it must name itself rather than surface as an
                # opaque numpy concatenate error.
                assert tr, (f"empty training set for held-out {held} in fold '{fname}' "
                            f"(fold size {len(g)}) — a fold must be a GROUP, not one slide")
                Xtr = np.concatenate([feats(D[s], arm) for s in tr])
                ytr = np.concatenate([D[s]["y"] for s in tr])
                for C in Cs:
                    res = fit_score(Xtr, ytr, feats(D[held], arm), D[held]["y"], a.seed,
                                    a.estimator, C, pca=a.pca, penalty=a.penalty,
                                    l1_ratio=a.l1_ratio, return_pred=bool(a.dump_percell))
                    f1, acc, per = res[0], res[1], res[2]
                    rows.append(dict(arm=arm, estimator=a.estimator, C=C, pca=a.pca,
                                     penalty=a.penalty, fold=fname, held=held,
                                     macro_f1=round(f1, 5), acc=round(acc, 5),
                                     **{f"f1_{c}": per.get(c) for c in CLASSES}))
                    if a.dump_percell:
                        yhat, proba, pcols = res[3], res[4], res[5]
                        blk = pd.DataFrame({
                            "arm": arm, "estimator": a.estimator, "C": C, "pca": a.pca,
                            "fold": fname, "held": held,
                            "row_idx": D[held]["row_idx"],
                            "object_id": D[held]["object_id"],
                            "y_true": D[held]["y"], "y_pred": yhat})
                        if proba is not None:
                            for j, c in enumerate(pcols):
                                blk[f"p_{c}"] = proba[:, j].astype(np.float32)
                        pc_rows.append(blk)
        mf = np.mean([r["macro_f1"] for r in rows if r["arm"] == arm])
        cfg = f" pca={a.pca}" if a.pca else ""
        cfg += f" penalty={a.penalty}" if a.penalty != "l2" else ""
        print(f"  [typing/{a.estimator}{cfg}] {arm:10s} LOPO macro-F1 = {mf:.4f}", flush=True)
    tf = pd.DataFrame(rows); tf.to_csv(f"{a.out}/typing_{a.tag}.tsv", sep="\t", index=False)

    # ---------- (1a) PER-CELL DUMP + its own regression gate  [2026-08-24]
    if a.dump_percell:
        from sklearn.metrics import f1_score as _f1
        pc = pd.concat(pc_rows, ignore_index=True)
        # GATE: re-derive macro-F1 per (arm, C, fold, held) from the DUMPED predictions and require
        # an exact match against typing_*.tsv. If this passes, the dump provably IS the prediction
        # vector the published metrics were computed from -- not a re-run that happens to agree.
        labs = sorted(CLASSES)
        chk = (pc.groupby(["arm", "C", "fold", "held"], sort=False)
                 .apply(lambda g: round(float(_f1(g.y_true, g.y_pred, average="macro",
                                                  labels=labs)), 5))
                 .rename("macro_f1_from_dump").reset_index())
        mg = tf.merge(chk, on=["arm", "C", "fold", "held"], how="inner")
        assert len(mg) == len(chk), f"dump/TSV key mismatch: {len(mg)} vs {len(chk)}"
        bad = mg[mg.macro_f1 != mg.macro_f1_from_dump]
        assert bad.empty, ("per-cell dump does not reproduce typing_*.tsv macro_f1 -- "
                           f"{len(bad)} rows disagree, worst "
                           f"{(bad.macro_f1 - bad.macro_f1_from_dump).abs().max():.10f}\n"
                           f"{bad.head().to_string()}")
        pc.to_parquet(f"{a.out}/percell_{a.tag}.parquet", index=False)
        n_arms = pc.arm.nunique()
        print(f"  [percell] GATE PASS: macro-F1 re-derived from {len(pc):,} dumped predictions "
              f"reproduces typing_{a.tag}.tsv exactly on all {len(chk)} (arm,C,fold) cells", flush=True)
        print(f"  [percell] wrote percell_{a.tag}.parquet  rows={len(pc):,} arms={n_arms} "
              f"cols={list(pc.columns)}", flush=True)
        # A cross-arm comparison is only meaningful if the arms scored the SAME cells. They do,
        # because one build() call feeds every arm -- asserted rather than assumed.
        if n_arms > 1:
            sig = {arm: tuple(g.sort_values(["held", "row_idx"]).row_idx.tolist())
                   for arm, g in pc[pc.C == pc.C.iloc[0]].groupby("arm")}
            base = next(iter(sig.values()))
            assert all(v == base for v in sig.values()), \
                "arms did not score identical cells -- cross-arm error overlap would be invalid"
            print(f"  [percell] cell-set identity across {n_arms} arms: PASS", flush=True)

    # ---------- (1b) RANDOM-30: within-distribution diagnostic, WITHIN fold, then averaged
    rrows = []
    if a.random30:
        from sklearn.model_selection import train_test_split
        for arm in ARMS:
            per_fold = []
            for fname, g in folds:
                X = np.concatenate([feats(D[s], arm) for s in g])
                y = np.concatenate([D[s]["y"] for s in g])
                itr, ite = train_test_split(np.arange(len(y)), test_size=0.30,
                                            random_state=a.seed, stratify=y)
                # random-30 mirrors the typing config, else the GAP would compare two different
                # readouts rather than two different splits.
                f1, acc, _ = fit_score(X[itr], y[itr], X[ite], y[ite], a.seed, a.estimator,
                                       pca=a.pca, penalty=a.penalty, l1_ratio=a.l1_ratio)
                per_fold.append(f1)
                rrows.append(dict(arm=arm, estimator=a.estimator, fold=fname,
                                  random30_macro_f1=round(f1, 5), acc=round(acc, 5),
                                  n_train=int(len(itr)), n_test=int(len(ite))))
            lopo_mean = float(np.mean([r["macro_f1"] for r in rows if r["arm"] == arm]))
            print(f"  [random30/{a.estimator}] {arm:10s} = {np.mean(per_fold):.4f}  "
                  f"gap vs LOPO = {np.mean(per_fold) - lopo_mean:+.4f}", flush=True)
        pd.DataFrame(rrows).to_csv(f"{a.out}/random30_{a.tag}.tsv", sep="\t", index=False)

    # ---------- (2) SLIDE IDENTITY: 12-way, random 70/30 over cells (chance 1/12 = 0.0833)
    rng = np.random.default_rng(a.seed + 1)
    srows = []
    for arm in ARMS:
        Xs, ys = [], []
        for s in slides:
            f = feats(D[s], arm)
            idx = rng.choice(len(f), min(a.slideid_n, len(f)), replace=False)
            Xs.append(f[idx]); ys.append(np.full(len(idx), s))
        X = np.concatenate(Xs); y = np.concatenate(ys)
        perm = rng.permutation(len(X)); cut = int(0.7 * len(X))
        tr, te = perm[:cut], perm[cut:]
        # ALWAYS logistic — see --estimator help. This is a feature-set property, not an estimator one.
        _, acc, _ = fit_score(X[tr], y[tr], X[te], y[te], a.seed, "logistic")
        srows.append(dict(arm=arm, slide_id_acc=round(acc, 5), chance=round(1 / len(slides), 4),
                          n_train=int(len(tr)), n_test=int(len(te))))
        print(f"  [slide-id] {arm:10s} acc = {acc:.4f}  (chance {1/len(slides):.4f}, LOWER better)", flush=True)
    sf = pd.DataFrame(srows); sf.to_csv(f"{a.out}/slideid_{a.tag}.tsv", sep="\t", index=False)

    # ---------- verdict table
    # GUARD: never let the SUMMARY kill a 25-minute run again. 51223521 computed and WROTE both
    # TSVs, then died here on KeyError 'C' because the rows loop and this pivot had diverged.
    if "C" not in tf.columns:
        tf = tf.assign(C=1.0)
    piv = tf.pivot_table(index="arm", columns="C", values="macro_f1", aggfunc="mean").round(4)
    print("\n=== macro-F1 by arm x C (⚠ read the BEST-C column per arm, not a fixed C) ===")
    print(piv.to_string())
    best = tf.groupby(["arm", "C"]).macro_f1.mean().reset_index()
    best = best.loc[best.groupby("arm").macro_f1.idxmax()].set_index("arm")
    summ = best[["macro_f1", "C"]].rename(columns={"macro_f1": "mean", "C": "best_C"}).round(4)
    summ = summ.join(tf.groupby("arm").macro_f1.std().round(4).rename("std")) \
               .join(sf.set_index("arm").slide_id_acc)
    if rrows:
        summ = summ.join(pd.DataFrame(rrows).groupby("arm").random30_macro_f1.mean().round(4))
        summ["gap_random30_minus_lopo"] = (summ["random30_macro_f1"] - summ["mean"]).round(4)
    if "m" in summ.index:
        base_f1 = summ.loc["m", "mean"]; base_sid = summ.loc["m", "slide_id_acc"]
        summ["d_f1_vs_m"] = (summ["mean"] - base_f1).round(4)
        summ["d_slideid_vs_m"] = (summ["slide_id_acc"] - base_sid).round(4)
        summ["WIN"] = np.where((summ["d_f1_vs_m"] > 0) & (summ["d_slideid_vs_m"] <= 0), "YES", "no")
    else:
        # one-arm-per-array-task runs have no `m` in scope; the consolidator joins across tasks.
        print("⚠ arm `m` not in this run — d_f1_vs_m / WIN deferred to the consolidator.")
    print("\n=== VERDICT (an arm WINS only if typing rises AND slide-id does not) ===")
    print(summ.to_string())
    print("\n⚠ m+r == m+mu in span (Trap 2) — not independent evidence.")
    print("⚠ typing trains on 5 slides (Trap 1), so absolute F1 is NOT comparable to historical ~0.62.")
    summ.to_csv(f"{a.out}/verdict_{a.tag}.tsv", sep="\t")

    json.dump({"generated": time.strftime("%Y-%m-%dT%H:%M:%S"), "cache": a.cache, "mu_dir": a.mu_dir,
               "fold_lists": a.fold_lists, "labels": a.labels, "fov": a.fov, "k": a.k,
               "per_slide": a.per_slide, "slideid_n": a.slideid_n, "seed": a.seed,
               "slides": slides, "arms": {k: v for k, v in ARMS.items()},
               "estimator": a.estimator,
               "estimator_spec": {
                   "logistic": "LogisticRegression multinomial C=1.0 class_weight=balanced max_iter=300",
                   "nystroem": "Nystroem(rbf, n_components=1024, gamma=1/median pairwise sq dist on a "
                               "2000-cell TRAIN subsample) -> the same LogisticRegression",
                   "mlp": "MLPClassifier(hidden=(256,), early_stopping=True, max_iter=300); balances "
                          "by UPSAMPLING to the majority count (no class_weight/sample_weight support)",
                   "histgb": "HistGradientBoostingClassifier(max_iter=200, lr=0.1, max_leaf_nodes=31), "
                             "balanced via sample_weight; NO StandardScaler (trees are scale-free)",
                   "knn": "KNeighborsClassifier(n_neighbors=15, metric=cosine); NO class balancing "
                          "is possible — DIAGNOSTIC arm",
               }[a.estimator],
               "all_hyperparameters_fixed_not_tuned": True,
               "slideid_estimator": "logistic (ALWAYS, independent of --estimator)",
               "random30": ("within-fold pooled cells, stratified 70/30, averaged over the 2 folds — "
                            "WITHIN-DISTRIBUTION diagnostic (same-slide cells in train and test), NOT "
                            "generalization. Differs from classifier_sweep_lopo.py, which pools all "
                            "12 slides; the two are NOT cross-comparable.") if a.random30 else None,
               "typing_split": "WITHIN-FOLD leave-one-slide-out (trains on 5) — avoids the indirect "
                               "leak described in Trap 1",
               "slideid_split": "random 70/30 over cells, 12-way, chance 0.0833, LOWER is better",
               "wall_s": round(time.time() - t0, 1)},
              open(f"{a.out}/PROVENANCE_{a.tag}.json", "w"), indent=1)
    print(f"\nwrote {a.out}/{{typing,slideid,verdict}}_{a.tag}.tsv  ({time.time()-t0:.0f}s)")


