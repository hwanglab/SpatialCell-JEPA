#!/usr/bin/env python
"""
p2_typing_and_slideid.py — P16 T2 · does the Phase-2 predictor's +0.225 R2 become a BETTER CELL
REPRESENTATION, or is it just better reconstruction?

Phase 2 showed clean-split mu reaches R2 = 0.6195 vs a two-ring ridge at 0.3949. That is embedding
RECONSTRUCTION. This script asks the only question that matters downstream:

  (1) CELL TYPING   macro-F1, 3 classes {Tumor, Immune, Stromal}
  (2) SLIDE IDENTITY   12-way accuracy, chance 1/12 = 0.0833, LOWER IS BETTER

★ (2) IS MANDATORY AND NOT OPTIONAL. Cell types are spatially autocorrelated (Moran's I 0.637), so
SMOOTHING RAISES TYPING F1 -- `logs2_only`, a second moment carrying no cell identity at all, already
beat the raw embedding (0.588-0.595 vs 0.580-0.585). And every smoothing arm we have measured made
slide identity monotonically WORSE (frozen 0.598 -> m+mu 0.673 -> m+smooth 0.735). An arm counts as a
win ONLY if typing rises AND slide identity does not.

⚠⚠ TRAP 1 — WHY THERE IS NO PLAIN 12-SLIDE LOPO HERE. mu for a slide in fold B was produced by the
predictor trained on fold A. So if we held out slide s in fold A and trained the typing probe on the
other 11, the fold-B slides' features would have been generated by a predictor that TRAINED ON s.
That is an indirect leak of the held-out slide into the training features. Instead we do
WITHIN-FOLD leave-one-slide-out: hold out one fold-B slide, train on the other 5 fold-B slides --
every one of those mu came from the fold-A-trained predictor, which never saw ANY fold-B slide.
Consequence: the probe trains on 5 slides, not 11, so ABSOLUTE macro-F1 is NOT comparable to the
historical ~0.62 numbers. All arms share the handicap, so the CONTRASTS are valid.

⚠⚠ TRAP 2 — [m + r] IS NOT A NEW ARM. r = m - mu, so span([m, r]) == span([m, mu]) exactly: for a
LINEAR probe the two are the same model up to regularisation. It is reported anyway (regularisation
does differ) but it must NOT be presented as independent evidence. The informative residual arm is
`r` ALONE, which is a genuinely different 1536-d subspace from `mu` alone.

ARMS (all on identical cells and folds)
  m            raw H-optimus-0 m_cell @fov112                        1536   baseline
  mu           the predictor's context-only prediction               1536   sees no cell pixels
  r            m - mu, the residual                                  1536   cell-specific part
  smooth       plain mean of the 36 nearest neighbours               1536   TRIVIAL control for mu
  m+mu         concatenation                                         3072
  m+smooth     concatenation                                         3072   TRIVIAL control for m+mu
  m+r          concatenation                                         3072   == m+mu in span (Trap 2)

estimator  --estimator, default `logistic` = LogisticRegression(multinomial, class_weight=balanced,
           max_iter=300, C=1.0), fixed, NOT tuned. The default path is BIT-IDENTICAL to the
           pre-2026-08-14 script.
unit / n   one labelled qc_pass cell; --per-slide cap
split      typing: WITHIN-FOLD leave-one-slide-out (see Trap 1).  slide-id: random 70/30 over cells.

★ NONLINEAR ESTIMATORS (added 2026-08-14, [user] request). The M=1-vs-M=12 null measured on
2026-08-13 (mu_bar - mu = +0.0002, 95% CI [-0.0019,+0.0024]) was established under a LINEAR probe
only, and a linear readout can be blind to a difference in mu that a nonlinear one registers. All
four are deliberately LOW-CAPACITY: with 12 slides and a +0.10 random-vs-LOPO gap, extra capacity
buys within-slide structure that does not transfer.

  logistic   multinomial LR, class_weight=balanced                 -- the incumbent, reference row
  nystroem   Nystroem(RBF, 1024 comp) -> the SAME LR               -- ★ minimal departure: identical
             gamma = 1/median(pairwise sq dist) on a TRAIN subsample   estimator/balancing/C, only the
                                                                       feature map changes, so any
                                                                       delta is nonlinearity alone
  mlp        MLPClassifier(hidden=(256,), early_stopping)          -- ⚠ supports NEITHER class_weight
                                                                       NOR sample_weight; balances by
                                                                       UPSAMPLING. Confound vs others.
  histgb     HistGradientBoostingClassifier(200 iters, lr 0.1)     -- balanced via sample_weight; no
                                                                       scaler (trees are scale-free)
  knn        KNeighborsClassifier(k=15, cosine)                    -- ⚠ DIAGNOSTIC: zero training, no
                                                                       class balancing possible. Asks
                                                                       whether types are locally
                                                                       clustered in embedding space.

⚠ RANDOM-30 IS A WITHIN-DISTRIBUTION DIAGNOSTIC, NOT A COMPETITOR. Same-slide cells sit in train and
test. It exists to test the PRE-REGISTERED failure mode ("nonlinearity raises random-30 and NOT LOPO
=> the gap WIDENS"). Computed WITHIN each fold and averaged, so mu provenance matches the LOPO arm
exactly -- this differs from classifier_sweep_lopo.py, which pools all 12 slides. The two random-30
numbers are therefore NOT cross-comparable.
"""
import argparse, glob, json, os, sys, time
import numpy as np
import pandas as pd
from scipy.spatial import cKDTree

MPP = 0.2522
MAX_ITER = 2000   # 300 left lbfgs UNCONVERGED on the 3072-d concat arms
                  # (48 ConvergenceWarnings in 51224268) — an under-optimised wide arm
                  # is a DIFFERENT failure from wrong regularisation strength, and the
                  # C sweep could not have fixed it.
CLASSES = ["Immune", "Stromal", "Tumor"]


def build(cache, mu_dirs, labels, fov, k, per_slide, seed, slides, agg_dirs=None, niche_dirs=None):
    rng = np.random.default_rng(seed)
    D = {}
    for s in slides:
        hits = [d for d in mu_dirs if os.path.exists(f"{d}/{s}.npz")]
        assert len(hits) == 1, f"{s}: mu found in {len(hits)} dirs {hits} (need exactly 1)"
        z = np.load(f"{cache}/{s}/{fov}/cells.npz")
        m_all = z["m_cell"].astype(np.float32)
        xy = z["centroid_xy"].astype(np.float32) * MPP
        # NB: `hits` holds DIRECTORIES; the file is <dir>/<slide>.npz.
        # Loading hits[0] directly raised IsADirectoryError and killed 51207366 in 10 s.
        mu_all = np.load(f"{hits[0]}/{s}.npz")["mu"]
        assert mu_all.shape == m_all.shape, f"{s}: mu {mu_all.shape} vs cache {m_all.shape}"
        lab = pd.read_parquet(f"{labels}/{s}.parquet")
        keep = np.where(lab.qc_pass.fillna(False).values & lab.L1.isin(CLASSES).values)[0]
        if len(keep) > per_slide:
            keep = rng.choice(keep, per_slide, replace=False)
        keep.sort()
        ri = lab.row_idx.values[keep]
        # smooth must use ALL cells as neighbours, not just labelled ones
        _, nn = cKDTree(xy).query(xy[ri], k=k + 2, workers=-1)
        sm = np.empty((len(ri), m_all.shape[1]), np.float32)
        for i, (row, self_i) in enumerate(zip(nn, ri)):
            sm[i] = m_all[row[row != self_i][:k]].mean(0)
        m, mu = m_all[ri], mu_all[ri].astype(np.float32)
        D[s] = dict(m=m, mu=mu, r=m - mu, smooth=sm, y=lab.L1.values[keep])
        # 2026-08-24: cell identity retained so --dump-percell can emit joinable per-cell rows.
        # NOT a feature: `feats()` only reads keys named in ARMS/AGG_ARMS, so these are inert for
        # every fit. They ride the agg_dirs `ok` filter below correctly (both are 1-D, axis 0).
        D[s]["row_idx"] = ri.astype(np.int64)
        D[s]["object_id"] = lab.object_id.values[keep]
        # ── NICHE-JEPA `z`  (T4 / G-006; added 2026-08-30) ────────────────────────────────────────
        # DEFAULT OFF and that is load-bearing: with --niche-dir absent, `z` is never loaded, ARMS is
        # untouched, and this file is BIT-IDENTICAL to the pre-2026-08-30 path, so the standing
        # m = 0.6159 harness-drift gate and every v1 number are undisturbed.
        # ⚠ `mu` for a niche run comes through the EXISTING loader above -- apply_niche_jepa.py writes
        #   its mu under the same "mu" key -- so --mu-dir should POINT AT THE SAME niche dir. Only `z`
        #   is new. That keeps one loader, one shape assert, one provenance path.
        # ⚠⚠ z is dz-dimensional (32-1024) vs m's 1536, so `m` vs `z` is a DIMENSION-CONFOUNDED
        #   contrast unless --pca is matched. Always report the pca-matched cell alongside.
        if niche_dirs:
            nh = [d for d in niche_dirs if os.path.exists(f"{d}/{s}.npz")]
            assert len(nh) == 1, f"{s}: niche z found in {len(nh)} dirs {nh} (need exactly 1)"
            gz = np.load(f"{nh[0]}/{s}.npz")
            assert "z" in gz.files, f"{nh[0]}/{s}.npz has {gz.files}, missing 'z'"
            zz = gz["z"]
            assert len(zz) == len(m_all), \
                f"{s}: z has {len(zz)} rows vs {len(m_all)} cached cells -- NOT row-aligned"
            D[s]["z"] = zz[ri].astype(np.float32)
            gz.close()
        if agg_dirs:
            ah = [d for d in agg_dirs if os.path.exists(f"{d}/{s}.npz")]
            assert len(ah) == 1, f"{s}: aggregated mu in {len(ah)} dirs (need exactly 1)"
            g = np.load(f"{ah[0]}/{s}.npz")
            kc = g["k_count"][ri]
            # a cell never sampled as a target has NaN -> it must not enter any arm
            ok = kc > 0
            if not ok.all():
                for key in list(D[s]):
                    D[s][key] = D[s][key][ok]
                ri, kc = ri[ok], kc[ok]
            D[s]["mu_bar"] = g["mu_bar"][ri].astype(np.float32)
            D[s]["V"] = g["var_mu"][ri].astype(np.float32)[:, None]      # scalar context-sensitivity
            D[s]["s2bar"] = g["s2_bar"][ri].astype(np.float32)[:, None]
            D[s]["r_bar"] = D[s]["m"] - D[s]["mu_bar"]
            print(f"      + aggregated: k_median={np.median(kc):.1f} dropped_unseen={int((~ok).sum())}",
                  flush=True)
        print(f"  {s:22s} n={len(ri):6d} " + "  ".join(f"{c}={int((D[s]['y']==c).sum())}" for c in CLASSES),
              flush=True)
    return D


ARMS = {"m": ["m"], "mu": ["mu"], "r": ["r"], "smooth": ["smooth"],
        "m+mu": ["m", "mu"], "m+smooth": ["m", "smooth"], "m+r": ["m", "r"]}
# added only when --niche-dir is supplied (T4 Niche-JEPA, 2026-08-30). `z` = the bottlenecked niche
# code; `mu` rides the existing loader. ⚠ Report ONLY beside `smooth`/`m+smooth` and the slide-ID
# readout: every smoothing arm this project has measured raised typing while making slide identity
# monotonically WORSE (frozen 0.598 -> m+smooth 0.735), and z is spatially autocorrelated BY
# CONSTRUCTION (two adjacent cells share ~34 of 36 neighbours).
NICHE_ARMS = {"z": ["z"], "m+z": ["m", "z"], "m+z+mu": ["m", "z", "mu"]}
# added only when --agg-dir is supplied (Phase-3b M=12 aggregated inference)
AGG_ARMS = {"mu_bar": ["mu_bar"], "m+mu_bar": ["m", "mu_bar"],
            "V": ["V"], "m+V": ["m", "V"], "m+mu_bar+V": ["m", "mu_bar", "V"],
            "r_bar": ["r_bar"], "m+s2bar": ["m", "s2bar"]}


def feats(d, arm):
    return np.concatenate([d[p] for p in ARMS[arm]], axis=1)


def _median_gamma(X, seed, n=2000):
    """RBF gamma = 1 / median(pairwise squared distance), estimated on a TRAIN subsample only.

    Fixed by heuristic rather than tuned -- tuning it on held-out slides would be exactly the
    contamination `feedback_holdout_contamination_no_tuning_on_validation` forbids.
    """
    rng = np.random.default_rng(seed)
    idx = rng.choice(len(X), min(n, len(X)), replace=False)
    S = X[idx].astype(np.float32)
    sq = (S * S).sum(1)
    d2 = np.maximum(sq[:, None] + sq[None, :] - 2.0 * (S @ S.T), 0.0)
    med = float(np.median(d2[np.triu_indices(len(S), k=1)]))
    return 1.0 / med if med > 0 else 1.0


def _balanced_w(y):
    cls, cnt = np.unique(y, return_counts=True)
    w = {c: len(y) / (len(cls) * n) for c, n in zip(cls, cnt)}
    return np.array([w[v] for v in y], dtype=np.float64)


def fit_score(Xtr, ytr, Xte, yte, seed, kind="logistic", C=1.0, pca=0, penalty="l2",
              l1_ratio=0.5, return_pred=False):
    """Returns (macro_f1, accuracy, per-class f1 dict). `kind` defaults to the incumbent logistic,
    so every pre-2026-08-14 call site is unchanged.

    2026-08-15 [user] added `pca` and `penalty` to test whether the `m+mu` concat deficit under the
    LINEAR probe is a dimensionality / collinearity effect.
      pca=N>0   -> TruncatedSVD-style randomized PCA to N components, FIT ON THE TRAINING SPLIT ONLY
                   and applied to both. Fitting it on the held-out slide would leak.
                   Motivation: mu is TRAINED to predict m, so [m, mu] is two near-collinear 1536-d
                   blocks and StandardScaler gives all 3072 dims equal weight. PCA attacks that
                   redundancy; L2 shrinkage cannot (measured flat, span <=0.0036 over C 0.01->1.0
                   in results/reports/20260814_ownknn_typing_Csweep/).
      penalty   -> l1 / elasticnet test SPARSITY rather than shrinkage. Both force solver='saga'.
                   ⚠ saga on 3072-d x ~132k rows is SLOW -- run these as separate array tasks.
    Defaults (pca=0, penalty='l2') keep the pre-2026-08-15 path bit-identical."""
    from sklearn.preprocessing import StandardScaler
    from sklearn.linear_model import LogisticRegression
    from sklearn.metrics import f1_score, accuracy_score

    if kind == "histgb":
        # trees are scale-free -> no scaler (also avoids a full float copy of a 3072-d matrix)
        from sklearn.ensemble import HistGradientBoostingClassifier
        clf = HistGradientBoostingClassifier(max_iter=200, learning_rate=0.1, max_leaf_nodes=31,
                                             random_state=seed)
        clf.fit(Xtr, ytr, sample_weight=_balanced_w(ytr))
        p = clf.predict(Xte)
    else:
        sc = StandardScaler().fit(Xtr)
        Ztr, Zte = sc.transform(Xtr), sc.transform(Xte)
        if pca and pca > 0:
            # ⚠ FIT ON TRAIN ONLY. n_components must be < min(n_samples, n_features).
            from sklearn.decomposition import PCA
            nc = min(pca, Ztr.shape[1], Ztr.shape[0] - 1)
            pc = PCA(n_components=nc, svd_solver="randomized", random_state=seed).fit(Ztr)
            Ztr, Zte = pc.transform(Ztr), pc.transform(Zte)
        if kind == "logistic":
            solver = "lbfgs" if penalty == "l2" else "saga"
            kw = dict(l1_ratio=l1_ratio) if penalty == "elasticnet" else {}
            clf = LogisticRegression(max_iter=MAX_ITER, C=C, class_weight="balanced", penalty=penalty,
                                     solver=solver, random_state=seed, **kw).fit(Ztr, ytr)
            p = clf.predict(Zte)
        elif kind == "nystroem":
            from sklearn.kernel_approximation import Nystroem
            # ⚠ n_components MUST stay < n_samples: when equal, sklearn falls back to the FULL kernel
            # and the fit becomes O(n^2) (148 s on a 1000-row unit test, 2026-08-14).
            ny = Nystroem(kernel="rbf", gamma=_median_gamma(Ztr, seed),
                          n_components=min(1024, len(Ztr) - 1),
                          random_state=seed).fit(Ztr)
            clf = LogisticRegression(max_iter=MAX_ITER, C=C, class_weight="balanced",
                                     random_state=seed).fit(ny.transform(Ztr), ytr)
            p = clf.predict(ny.transform(Zte))
        elif kind == "mlp":
            from sklearn.neural_network import MLPClassifier
            # MLPClassifier takes neither class_weight nor sample_weight -> upsample to the majority
            rng = np.random.default_rng(seed)
            cls, cnt = np.unique(ytr, return_counts=True)
            take = np.concatenate([rng.choice(np.where(ytr == c)[0], cnt.max(), replace=True)
                                   for c in cls])
            rng.shuffle(take)
            # ⚠ STRING labels + early_stopping crash this sklearn build: _score_with_function calls
            # np.isnan(y_pred) on a str array -> TypeError. Encode to int, decode after. (2026-08-14)
            codes = {c: i for i, c in enumerate(cls)}
            ytr_i = np.array([codes[v] for v in ytr[take]], dtype=np.int32)
            clf = MLPClassifier(hidden_layer_sizes=(256,), early_stopping=True, max_iter=300,
                                random_state=seed).fit(Ztr[take], ytr_i)
            p = np.array(cls)[clf.predict(Zte)]
        elif kind == "knn":
            from sklearn.neighbors import KNeighborsClassifier
            clf = KNeighborsClassifier(n_neighbors=15, metric="cosine").fit(Ztr, ytr)
            p = clf.predict(Zte)
        else:
            raise ValueError(f"unknown estimator {kind}")

    labs = sorted(set(ytr) | set(yte))
    out = (float(f1_score(yte, p, average="macro", labels=labs)),
           float(accuracy_score(yte, p)),
           {c: round(float(v), 4) for c, v in zip(labs, f1_score(yte, p, average=None, labels=labs))})
    if not return_pred:
        return out
    # 2026-08-24: `p` is the SAME prediction vector the three metrics above were computed from, so a
    # dump built here cannot disagree with the TSV. The regression gate re-derives macro-F1 from the
    # dumped column and requires an exact match, which is what makes that guarantee checkable.
    # `clf` is bound in every branch above. predict_proba is absent on some estimators -> None.
    try:
        proba, proba_cols = clf.predict_proba(_Zte_for_proba(kind, locals())), list(clf.classes_)
    except Exception:
        proba, proba_cols = None, None
    return out + (np.asarray(p), proba, proba_cols)


def _Zte_for_proba(kind, ns):
    """The transformed test matrix that was actually fed to `clf.predict` in each branch."""
    if kind == "histgb":
        return ns["Xte"]
    if kind == "nystroem":
        return ns["ny"].transform(ns["Zte"])
    return ns["Zte"]


