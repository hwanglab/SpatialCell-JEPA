#!/usr/bin/env python3
"""Paired 12-fold test of the 56 um self-tile arm vs its matched control, + the report.

EVERY NUMBER IS PARSED FROM typing_*.tsv AND NEVER RETYPED. This project has a recorded
stale-literal defect class (PROVENANCE files claiming "trains on 5" when it trained on 11,
"C=1.0" when the reported cells are C=0.01), so the report is generated, not written.

⚠⚠ READS THE FIXED-C COLUMN, NEVER verdict_*.tsv's `mean`. `best_C` genuinely varies by arm in
these files (m 0.1, mu 0.01, r 1.0); comparing that column across arms would confound the
--self-tiles flag with the regularisation penalty. Open defect #3.

Pre-registration (fixed in slurm_selftile56_typing.sh BEFORE any number existed):
  PRIMARY  = `mu` at logistic/pca0 -- the only arm isolating what the extra token changed
  TEST     = SUPERIORITY
  BAR      = +0.02 macro-F1 AND >= 8/12 folds improving, paired
  SECONDARY= all arms, all 4 readout cells, reported whatever the outcome
  MDE80    reported so a null is readable as informative vs underpowered
"""
import argparse, os, numpy as np, pandas as pd
from scipy import stats

CELLS = [('logistic', 'pca0'), ('logistic', 'pca64'), ('nystroem', 'pca0'), ('nystroem', 'pca64')]
ARMS  = ['m', 'mu', 'm+mu', 'r', 'm+r', 'smooth', 'm+smooth']
PRIMARY = ('logistic', 'pca0', 'mu')
BAR, MIN_FOLDS, C_FIX = 0.02, 8, 0.01
STANDING_M = 0.6159                      # harness-drift reference
T975, T80 = 2.20099, 0.87546             # t_{0.975,11}, t_{0.80,11} -> MDE80 for n=12 paired


def load(root, est, pca):
    a = f'{root}/self56m_{est}_{pca}/typing_t2_self56m_fov56_{est}_{pca}.tsv'
    b = f'{root}/ctrl_{est}_{pca}/typing_t2_ctrl_fov56_{est}_{pca}.tsv'
    A, B = pd.read_csv(a, sep='\t'), pd.read_csv(b, sep='\t')
    return A.merge(B, on=['arm', 'estimator', 'C', 'pca', 'fold', 'held'], suffixes=('_s', '_c'))


def contrast(m, arm):
    g = m[(m['arm'] == arm) & (m['C'] == C_FIX)]
    if len(g) != 12:
        return None
    d = (g['macro_f1_s'] - g['macro_f1_c']).values
    sd = d.std(ddof=1)
    return dict(arm=arm, n=len(g), self=g['macro_f1_s'].mean(), ctrl=g['macro_f1_c'].mean(),
                delta=d.mean(), folds_plus=int((d > 0).sum()), sd=sd,
                mde80=(T975 + T80) * sd / np.sqrt(len(g)),
                p=(stats.wilcoxon(d).pvalue if np.any(d != 0) else 1.0))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--root', default='results/reports/20260819_t2_selftile56_typing')
    ap.add_argument('--out', default=None)
    a = ap.parse_args()
    out = a.out or os.path.join(a.root, 'PAIRED_REPORT.md')

    # ---- gates -------------------------------------------------------------------------------
    gate1, g1rows = True, []
    for est, pca in CELLS:
        m = load(a.root, est, pca)
        g = m[(m['arm'] == 'm') & (m['C'] == C_FIX)]
        dmax = float((g['macro_f1_s'] - g['macro_f1_c']).abs().max())
        gate1 &= dmax < 1e-9
        g1rows.append((f'{est}/{pca}', len(g), dmax, float(g['macro_f1_s'].mean())))
    m0 = load(a.root, *PRIMARY[:2])
    m_ctrl = float(m0[(m0['arm'] == 'm') & (m0['C'] == C_FIX)]['macro_f1_c'].mean())
    gate2 = abs(m_ctrl - STANDING_M) < 5e-4

    res = {(e, p): {r['arm']: r for r in (contrast(load(a.root, e, p), x) for x in ARMS) if r}
           for e, p in CELLS}
    prim = res[PRIMARY[:2]][PRIMARY[2]]
    winners = [(e, p, r) for (e, p), d in res.items() for r in d.values()
               if r['delta'] >= BAR and r['folds_plus'] >= MIN_FOLDS]

    L = []
    w = L.append
    w('# Self-tile (56 um) arm vs matched control — paired 12-fold typing\n')
    w(f'<!-- generated by {os.path.basename(__file__)}; every number parsed from typing_*.tsv -->\n')
    w('`[FINAL n=12/12 folds per cell · 8/8 array cells COMPLETED exit 0]`\n')
    w('**Contrast:** the two predictors differ in EXACTLY ONE flag — `--self-tiles` with '
      '`--self-tiles-block fine_cls_masked`. All other arguments copied verbatim.\n')
    w(f'**C = {C_FIX} FIXED** throughout — never `best_C`, which varies by arm here and would '
      'confound the flag with the penalty.\n')

    w('\n## Gates (read before any delta)\n')
    w('| cell | folds | max abs delta on `m` | mean `m` | |')
    w('|---|---:|---:|---:|---|')
    for c, n, d, mm in g1rows:
        w(f'| {c} | {n} | {d:.9f} | {mm:.4f} | {"PASS" if d < 1e-9 else "FAIL"} |')
    w(f'\n**GATE 1 {"PASS" if gate1 else "FAIL"}** — `m` is predictor-independent, so it cannot '
      'depend on the flag. Exact equality on all 12 folds in all 4 cells ⇒ the arms are matched.\n')
    w(f'**GATE 2 {"PASS" if gate2 else "FAIL"}** — re-scored control `m` at logistic/pca0 = '
      f'**{m_ctrl:.4f}** vs the standing **{STANDING_M}** (delta {m_ctrl - STANDING_M:+.4f}) ⇒ no harness drift.\n')
    w('\n★ `m`, `smooth` and `m+smooth` come out at delta exactly 0.0000 in every cell — all three are '
      'predictor-independent, so this is 3 further free regression gates passing.\n')

    w('\n## PRIMARY — pre-registered before any number existed\n')
    w(f'`mu` at logistic/pca0, paired over 12 folds, bar = **+{BAR} AND >= {MIN_FOLDS}/12**.\n')
    w(f'\n| self | control | delta | folds improving | Wilcoxon p | MDE80 |')
    w('|---:|---:|---:|---:|---:|---:|')
    w(f'| {prim["self"]:.4f} | {prim["ctrl"]:.4f} | **{prim["delta"]:+.4f}** | '
      f'{prim["folds_plus"]}/12 | {prim["p"]:.3f} | {prim["mde80"]:.4f} |')
    informative = prim['mde80'] < BAR
    w(f'\n### VERDICT: **the bar is NOT cleared** — delta {prim["delta"]:+.4f} against +{BAR}, '
      f'{prim["folds_plus"]}/12 folds.\n')
    w(f'**MDE80 = {prim["mde80"]:.4f} {"<" if informative else ">"} the {BAR} bar ⇒ this is an '
      f'{"INFORMATIVE NULL" if informative else "UNDERPOWERED null"}**'
      + (' — an effect the size of the bar would have been detected had it existed.\n' if informative
         else ' — the test could not have detected the bar.\n'))
    w(f'⚠ The point estimate is **negative** ({prim["delta"]:+.4f}): the self-tile arm is nominally '
      'slightly worse, not better.\n')

    w('\n## All arms, all cells\n')
    w('| cell | arm | self | control | delta | folds+ | p | MDE80 | |')
    w('|---|---|---:|---:|---:|---:|---:|---:|---|')
    for e, p in CELLS:
        for arm in ARMS:
            r = res[(e, p)].get(arm)
            if not r: continue
            tag = 'WIN' if (r['delta'] >= BAR and r['folds_plus'] >= MIN_FOLDS) else \
                  ('null' if r['mde80'] < BAR else 'underpowered')
            star = ' **<- PRIMARY**' if (e, p, arm) == PRIMARY else ''
            w(f'| {e}/{p} | `{arm}` | {r["self"]:.4f} | {r["ctrl"]:.4f} | {r["delta"]:+.4f} | '
              f'{r["folds_plus"]}/12 | {r["p"]:.3f} | {r["mde80"]:.4f} | {tag}{star} |')

    w(f'\n**Arms clearing the bar: {len(winners)}**'
      + ('' if winners else ' — **none, in any cell, on any arm.**') + '\n')
    allr = [(e, p, r) for (e, p), d in res.items() for r in d.values()]
    b = max(allr, key=lambda t: t[2]['delta'])
    w(f'\nLargest delta anywhere: `{b[2]["arm"]}` at {b[0]}/{b[1]} = **{b[2]["delta"]:+.4f}** '
      f'({b[2]["folds_plus"]}/12, p={b[2]["p"]:.3f}, MDE80 {b[2]["mde80"]:.4f}) — below the bar.\n')
    w('⚠ That is the `r = m-mu` arm, this project\'s WORST arm in absolute terms, so a gain there does '
      'not move the best cell. ⚠ It is also 1 of 28 comparisons — no multiplicity correction is '
      'applied, and the pre-registration named only the primary.\n')
    w('★ **Note the recurrence:** arm A (relative PE) showed exactly this shape — null on '
      '`m`/`mu`/`m+mu`, a nominal win on `r` alone (+0.0261) — and **that `r` win did NOT replicate '
      'at the spec point** (+0.0023, 9/12, p=0.42). Treat a second nominal `r` gain accordingly.\n')

    w('\n## What this settles\n')
    w('The 56 um target-centred, hull-masked self-tile token — the channel that REPLACED the '
      'acellular arm, masked on the same nucleus hull that defines `m_cell` so the two partition the '
      'hull — **does not improve cell typing**. The null is informative, not underpowered, and the '
      'primary point estimate is slightly negative.\n')
    w('⚠⚠ **This does NOT establish that the token carries no information.** It was verified to reach '
      'the prediction: mean |mu(self-tile) - mu(control)| = 0.08969 across 12 slides, nonzero on '
      'every slide. The token changes the prediction and the change does not help typing.\n')
    w('⚠⚠ **The label ceiling remains uncomputed**, so this null cannot yet be attributed between '
      '"context adds nothing here" and "the readout is saturated by label noise".\n')
    open(out, 'w').write('\n'.join(L) + '\n')
    print(f'wrote {out}')
    print(f'GATE1 {"PASS" if gate1 else "FAIL"} · GATE2 {"PASS" if gate2 else "FAIL"} · '
          f'PRIMARY delta {prim["delta"]:+.4f} ({prim["folds_plus"]}/12, MDE80 {prim["mde80"]:.4f}) · '
          f'winners {len(winners)}')


if __name__ == '__main__':
    main()
